-- Core schema, written in SQL that both PostgreSQL and H2 accept.
-- The database is the source of truth; the in-memory linking state is
-- rebuilt from these tables on startup.

-- Every account the service has received, in arrival order (seq).
CREATE TABLE accounts (
    seq                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id          VARCHAR(128)             NOT NULL,
    email               VARCHAR(320)             NOT NULL,
    device_id           VARCHAR(256),
    ip                  VARCHAR(64)              NOT NULL,
    payment_fingerprint VARCHAR(256),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_accounts_account_id UNIQUE (account_id)
);

-- Pairs of accounts known to be different people (for example, both passed
-- identity verification). Stored once per pair, smaller ID first.
CREATE TABLE identity_constraints (
    account_a  VARCHAR(128)             NOT NULL,
    account_b  VARCHAR(128)             NOT NULL,
    relation   VARCHAR(32)              NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_identity_constraints PRIMARY KEY (account_a, account_b),
    CONSTRAINT ck_identity_constraints_order CHECK (account_a < account_b),
    CONSTRAINT ck_identity_constraints_relation CHECK (relation = 'verified_distinct')
);

-- An analyst's review of a cluster. Cluster IDs can be renumbered when the
-- state is rebuilt, so a decision also records exactly which accounts it covered.
CREATE TABLE analyst_decisions (
    decision_id UUID                     NOT NULL,
    cluster_id  VARCHAR(32)              NOT NULL,
    outcome     VARCHAR(32)              NOT NULL,
    analyst     VARCHAR(128)             NOT NULL,
    note        VARCHAR(2000),
    decided_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_analyst_decisions PRIMARY KEY (decision_id),
    CONSTRAINT ck_analyst_decisions_outcome CHECK (outcome IN ('CONFIRMED_FRAUD', 'NOT_FRAUD'))
);

CREATE TABLE decision_accounts (
    decision_id UUID         NOT NULL,
    account_id  VARCHAR(128) NOT NULL,
    CONSTRAINT pk_decision_accounts PRIMARY KEY (decision_id, account_id),
    CONSTRAINT fk_decision_accounts_decision FOREIGN KEY (decision_id) REFERENCES analyst_decisions (decision_id)
);
CREATE INDEX ix_decision_accounts_account ON decision_accounts (account_id);

-- Append-only record of every automated and human decision.
CREATE TABLE audit_events (
    event_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    event_type  VARCHAR(64)              NOT NULL,
    account_id  VARCHAR(128),
    cluster_id  VARCHAR(32),
    actor       VARCHAR(128)             NOT NULL,
    details     VARCHAR(4000)            NOT NULL
);
CREATE INDEX ix_audit_events_account ON audit_events (account_id, event_id);
CREATE INDEX ix_audit_events_cluster ON audit_events (cluster_id, event_id);
