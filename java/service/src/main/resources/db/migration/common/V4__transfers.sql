-- Money moved between accounts. Either side may be an account the bank does
-- not hold (for example a scam victim paying in from another bank), so neither
-- column references the accounts table. Transfers never change any cluster.
CREATE TABLE transfers (
    seq          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id  VARCHAR(128)             NOT NULL,
    from_account VARCHAR(128)             NOT NULL,
    to_account   VARCHAR(128)             NOT NULL,
    amount_cents BIGINT                   NOT NULL,
    occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_transfers_transfer_id UNIQUE (transfer_id),
    CONSTRAINT ck_transfers_amount CHECK (amount_cents > 0),
    CONSTRAINT ck_transfers_sides CHECK (from_account <> to_account)
);
CREATE INDEX ix_transfers_to ON transfers (to_account, occurred_at);
CREATE INDEX ix_transfers_from ON transfers (from_account, occurred_at);

-- When each account the bank holds was first flagged as a likely mule. Keeps
-- the "mule.flagged" audit event to once per account, and lets a later
-- NOT_FRAUD decision clear the flag.
CREATE TABLE mule_flags (
    account_id VARCHAR(128)             NOT NULL,
    flagged_at TIMESTAMP WITH TIME ZONE NOT NULL,
    score      DOUBLE PRECISION         NOT NULL,
    reasons    VARCHAR(512)             NOT NULL,
    CONSTRAINT pk_mule_flags PRIMARY KEY (account_id)
);
