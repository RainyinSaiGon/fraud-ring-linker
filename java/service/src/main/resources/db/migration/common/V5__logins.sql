-- Login attempts. The account may not be held yet (logins can arrive before the
-- sign-up does), so account_id does not reference the accounts table. Logins
-- never change any cluster. The location is where IP geolocation put the
-- address: both coordinates, or neither.
CREATE TABLE logins (
    seq         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id    VARCHAR(128)             NOT NULL,
    account_id  VARCHAR(128)             NOT NULL,
    device_id   VARCHAR(256),
    ip          VARCHAR(64),
    success     BOOLEAN                  NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    latitude    DOUBLE PRECISION,
    longitude   DOUBLE PRECISION,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_logins_login_id UNIQUE (login_id),
    CONSTRAINT ck_logins_location CHECK ((latitude IS NULL AND longitude IS NULL)
        OR (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180))
);
CREATE INDEX ix_logins_account ON logins (account_id, occurred_at);

-- When each account the bank holds was first flagged as a possible takeover.
-- Keeps the "takeover.flagged" audit event to once per account, and lets a
-- later takeover decision answer the flag.
CREATE TABLE takeover_flags (
    account_id VARCHAR(128)             NOT NULL,
    flagged_at TIMESTAMP WITH TIME ZONE NOT NULL,
    score      DOUBLE PRECISION         NOT NULL,
    reasons    VARCHAR(512)             NOT NULL,
    CONSTRAINT pk_takeover_flags PRIMARY KEY (account_id)
);

-- An analyst's decision about one account, not a cluster: a takeover harms one
-- real customer, so the rest of the cluster is left alone.
CREATE TABLE takeover_decisions (
    decision_id UUID                     NOT NULL,
    account_id  VARCHAR(128)             NOT NULL,
    outcome     VARCHAR(32)              NOT NULL,
    analyst     VARCHAR(128)             NOT NULL,
    note        VARCHAR(2000),
    decided_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_takeover_decisions PRIMARY KEY (decision_id),
    CONSTRAINT ck_takeover_decisions_outcome CHECK (outcome IN ('CONFIRMED_TAKEOVER', 'NOT_TAKEOVER'))
);
CREATE INDEX ix_takeover_decisions_account ON takeover_decisions (account_id, decided_at);
